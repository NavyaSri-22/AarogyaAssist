from sqlalchemy import create_engine, text

print("Aarogya Assist - Neon Database Setup")

database_url = input(
    "Paste your PostgreSQL connection string (kept only for this run): "
).strip()

if not database_url:
    raise ValueError("Connection string is empty. Please paste it.")

if database_url.startswith("postgresql://"):
    database_url = database_url.replace(
        "postgresql://",
        "postgresql+psycopg://",
        1
    )

print("Connection string received successfully.")
print("Connecting to Neon...")

engine = create_engine(database_url, pool_pre_ping=True)

tables = [
    """
    CREATE TABLE IF NOT EXISTS users (
        user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        full_name VARCHAR(100) NOT NULL,
        email VARCHAR(150) UNIQUE NOT NULL,
        password_hash VARCHAR(255) NOT NULL,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )
    """,

    """
    CREATE TABLE IF NOT EXISTS medical_reports (
        report_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(user_id),
        filename VARCHAR(255) NOT NULL,
        report_type VARCHAR(100) DEFAULT 'CBC',
        uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )
    """,

    """
    CREATE TABLE IF NOT EXISTS medical_parameters (
        parameter_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        report_id INTEGER NOT NULL REFERENCES medical_reports(report_id) ON DELETE CASCADE,
        test_name VARCHAR(100) NOT NULL,
        value NUMERIC(12,3),
        unit VARCHAR(50),
        reference_min NUMERIC(12,3),
        reference_max NUMERIC(12,3),
        status VARCHAR(50),
        reported_flag VARCHAR(50)
    )
    """,

    """
    CREATE TABLE IF NOT EXISTS report_explanations (
        explanation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        report_id INTEGER NOT NULL REFERENCES medical_reports(report_id) ON DELETE CASCADE,
        language VARCHAR(20) NOT NULL,
        explanation TEXT,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )
    """,

    """
    CREATE TABLE IF NOT EXISTS conversations (
        conversation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(user_id),
        title VARCHAR(255) DEFAULT 'New Conversation',
        language VARCHAR(20) DEFAULT 'English',
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )
    """,

    """
    CREATE TABLE IF NOT EXISTS chat_messages (
        message_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        conversation_id INTEGER NOT NULL REFERENCES conversations(conversation_id) ON DELETE CASCADE,
        role VARCHAR(20) NOT NULL CHECK (role IN ('user', 'assistant')),
        content TEXT NOT NULL,
        emergency_detected BOOLEAN DEFAULT FALSE,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )
    """
]

indexes = [
    "CREATE INDEX IF NOT EXISTS idx_reports_user ON medical_reports(user_id)",
    "CREATE INDEX IF NOT EXISTS idx_parameters_report ON medical_parameters(report_id)",
    "CREATE INDEX IF NOT EXISTS idx_explanations_report ON report_explanations(report_id)",
    "CREATE INDEX IF NOT EXISTS idx_conversations_user ON conversations(user_id)",
    "CREATE INDEX IF NOT EXISTS idx_messages_conversation ON chat_messages(conversation_id)"
]

try:
    with engine.begin() as connection:
        for statement in tables:
            connection.execute(text(statement))

        for statement in indexes:
            connection.execute(text(statement))

    print("\nSUCCESS! All six tables created in Neon.")

    with engine.connect() as connection:
        result = connection.execute(text("""
            SELECT table_name
            FROM information_schema.tables
            WHERE table_schema = 'public'
              AND table_type = 'BASE TABLE'
            ORDER BY table_name
        """))

        print("\nTables available in Neon:")
        for row in result:
            print("-", row[0])

except Exception as error:
    print("\nDatabase setup failed:")
    print(error)

finally:
    engine.dispose()
